// api/follow-up-cron.ts
//
// Vercel cron job — runs daily at 09:00 AEST (configured in vercel.json).
//
// Purpose: send the day-3 follow-up email to EOIs that:
//   - submitted ≥ 3 days ago
//   - status === 'new'  (no booking yet — booked EOIs get the booking pipe)
//   - followup_sent_at IS NULL  (don't double-send)
//
// Template selection (lead temperature):
//   HOT    → watched 90%+ of Loom AND hasn't booked   (rare but valuable)
//   WARM   → watched 75%+ of Loom, hasn't booked
//   COOL   → watched 25-75% of Loom
//   COLD   → watched <25% OR didn't open Loom
//
// Until Loom is filmed, watch_pct is always null, so everyone falls to COLD.
// That's the right default — the cold template doesn't assume they watched.
//
// Resend sender: notifications@hiretrial.com.au (Resend domain already
// verified via existing eoi-submit + approve-eoi routes).
//
// Security: Vercel automatically protects cron endpoints with a header
// `Authorization: Bearer <CRON_SECRET>`. We verify that header before
// running. CRON_SECRET is auto-generated by Vercel when cron is enabled.
//
// Env vars required:
//   SUPABASE_URL
//   SUPABASE_SERVICE_ROLE_KEY
//   RESEND_API_KEY
//   CRON_SECRET (auto-generated by Vercel when cron is enabled)
// ═══════════════════════════════════════════════════════════════════

