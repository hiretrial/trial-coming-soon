// ─── Lead temperature classifier ──────────────────────────────────
// Currently returns 'cold' for everyone (Loom not filmed yet).
// When Loom is live, this reads loom_watch_pct from the eoi row.
type Temperature = 'hot' | 'warm' | 'cool' | 'cold';

function classifyLead(eoi: any): Temperature {
  const watchPct = eoi.loom_watch_pct || 0;
  if (watchPct >= 90) return 'hot';
  if (watchPct >= 75) return 'warm';
  if (watchPct >= 25) return 'cool';
  return 'cold';
}

