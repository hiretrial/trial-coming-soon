function escapeHtml(s: string) {
  return String(s || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function fillTemplate(html: string, vars: { firstName: string; venueName: string }) {
  return html
    .replace(/\{\{firstName\}\}/g, vars.firstName)
    .replace(/\{\{venueName\}\}/g, vars.venueName);
}

// ─── Main handler ─────────────────────────────────────────────────
export default async function handler(req: VercelRequest, res: VercelResponse) {
  // Vercel cron sends a GET with Authorization: Bearer <CRON_SECRET>
  if (CRON_SECRET) {
    const auth = req.headers['authorization'];
    if (auth !== `Bearer ${CRON_SECRET}`) {
      console.warn('[follow-up-cron] Unauthorized request — missing or wrong CRON_SECRET');
      return res.status(401).json({ ok: false, error: 'Unauthorized' });
    }
  } else {
    console.warn('[follow-up-cron] CRON_SECRET not set — running unauthenticated (dev mode)');
  }

  // Env sanity
  if (!SUPABASE_URL || !SUPABASE_SERVICE_ROLE_KEY || !RESEND_API_KEY) {
    console.error('[follow-up-cron] Missing required env vars');
    return res.status(500).json({ ok: false, error: 'Server misconfiguration' });
  }

  const admin: any = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY);
  const resend = new Resend(RESEND_API_KEY);

  // ── 1. Find eligible EOIs ──────────────────────────────────────
  // Cutoff: created ≤ (now - FOLLOWUP_DAYS days)
  const cutoff = new Date(Date.now() - FOLLOWUP_DAYS * 24 * 60 * 60 * 1000).toISOString();

  const { data: eois, error: queryErr } = await admin
    .from('eoi_submissions')
    .select('id, email, contact_name, venue_name, created_at, status, calendly_booking_at, followup_sent_at, followup_attempts, loom_watch_pct')
    .eq('status', 'new')                         // hasn't booked
    .is('followup_sent_at', null)                // hasn't been sent yet
    .is('calendly_booking_at', null)             // belt-and-braces: not booked
    .lte('created_at', cutoff)                   // old enough
    .order('created_at', { ascending: true })    // oldest first
    .limit(50);                                  // safety cap per run

  if (queryErr) {
    console.error('[follow-up-cron] Query failed:', queryErr);
    return res.status(500).json({ ok: false, error: queryErr.message });
  }

  if (!eois || eois.length === 0) {
    console.log('[follow-up-cron] No EOIs eligible for follow-up today');
    return res.status(200).json({ ok: true, processed: 0 });
  }

  console.log(`[follow-up-cron] Found ${eois.length} EOIs eligible for follow-up`);

  // ── 2. Send each one (sequentially to avoid rate limits) ───────
  const results = { sent: 0, failed: 0, errors: [] as string[] };

  for (const eoi of eois) {
    try {
      const temperature = classifyLead(eoi);
      const template    = TEMPLATES[temperature];
      const firstName   = (eoi.contact_name || '').trim().split(/\s+/)[0] || 'there';
      const venueName   = eoi.venue_name || 'your venue';

      const vars = { firstName, venueName };
      const subject = fillTemplate(template.subject, vars);
      const html    = template.bodyHtml(vars);

      // Send via Resend
      const { data: sendData, error: sendErr } = await resend.emails.send({
        from:     FROM_ADDRESS,
        to:       eoi.email,
        replyTo:  REPLY_TO,
        subject,
        html,
        headers: {
          'X-Trial-Followup-Template': temperature,
          'X-Trial-EOI-ID':            eoi.id,
        },
      });

      if (sendErr) {
        console.error(`[follow-up-cron] Resend failed for ${eoi.email}:`, sendErr);
        results.failed++;
        results.errors.push(`${eoi.email}: ${sendErr.message || 'send error'}`);
        // Still bump the attempts counter so we can see the retries
        await admin.from('eoi_submissions')
          .update({ followup_attempts: (eoi.followup_attempts || 0) + 1, updated_at: new Date().toISOString() })
          .eq('id', eoi.id);
        continue;
      }

      // Mark as sent
      const { error: updErr } = await admin
        .from('eoi_submissions')
        .update({
          followup_sent_at:  new Date().toISOString(),
          followup_template: temperature,
          followup_attempts: (eoi.followup_attempts || 0) + 1,
          updated_at:        new Date().toISOString(),
        })
        .eq('id', eoi.id);

      if (updErr) {
        console.error(`[follow-up-cron] DB update failed for ${eoi.id}:`, updErr);
        // Email sent but DB didn't update — log and continue.
        // Next run won't pick it up because we'd hit a unique conflict if we tried,
        // but the data inconsistency is concerning. Worth monitoring.
      }

      results.sent++;
      console.log(`[follow-up-cron] ✅ ${temperature} → ${eoi.email} (${firstName}, ${venueName})`);

    } catch (err: any) {
      results.failed++;
      results.errors.push(`${eoi.email}: ${err.message || err}`);
      console.error(`[follow-up-cron] Unexpected error for ${eoi.email}:`, err);
    }
  }

  console.log(`[follow-up-cron] Done. Sent: ${results.sent}, Failed: ${results.failed}`);
  return res.status(200).json({
    ok: true,
    processed: eois.length,
    sent: results.sent,
    failed: results.failed,
    errors: results.errors,
  });
}
